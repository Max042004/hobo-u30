def test_preview_is_readonly_and_preserves_unedited_raw_rules_exactly():
    n=Native();raw=bytes.fromhex('0200270050014e8072000103010002000300');n.raws=[raw]
    s=snapshot(n);before=len(n.calls)
    p=preview_configuration({'normally':'closed','pulse_ms':30,'rules':[{'preserve_hex':raw.hex()}]},s)
    assert len(n.calls)==before and p['rules'][0]['raw_hex']==raw.hex()
    with pytest.raises(ValueError):preview_configuration({'normally':'open','pulse_ms':31,'rules':[]},s)
    with pytest.raises(ValueError):preview_configuration({'normally':'open','pulse_ms':30,'rules':[{'preserve_hex':'ff'*18}]},s)


def test_full_apply_backups_then_verifies_without_stopping_or_relaunching_logger(tmp_path):
    n=Native();p=plan(n)
    with patch('station.session',return_value=nullcontext(n.client)),patch('station.read_header',return_value=(HEADER,INFO)):
        result=apply_configuration(tmp_path,p)
    assert result['phase']=='verified' and result['after']['signature']==signature(p)
    assert result['before']['rules']==[]
    assert len(list(tmp_path.glob('*-alarms.json')))==1
    assert n.raws[0]==bytes.fromhex(p['rules'][0]['raw_hex'])
    writes=[(target,code) for target,code,_ in n.calls if (target,code) in ((7,3),(7,1),(8,1),(8,9))]
    assert writes==[(7,3),(8,1),(8,9),(7,1)]
    assert all(target in (7,8) for target,_,_ in n.calls)  # Never OSER D/F/B.


def test_changed_baseline_or_sensor_identity_prevents_first_write(tmp_path):
    n=Native();p=plan(n);n.normally=1
