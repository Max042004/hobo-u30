class Native:
    def __init__(self):
        self.raws=[];self.normally=0;self.pulse=100;self.current=0;self.calls=[];self.fail_number=None
        self.client=Mock(host_address=176)
        self.client.transport.transact.side_effect=self.transact
        self.client.attached_instruments.return_value=[CHANNEL["instrument"]]
        self.client.descriptor.return_value=parse_sensor_header(CHANNEL["instrument"],bytes.fromhex(CHANNEL["header_hex"]))
    def transact(self,host,target,code,payload,expected):
        self.calls.append((target,code,payload))
        if target==8:
            if code==3:data=bytes([self.normally])+self.pulse.to_bytes(4,"big")
            elif code==7:data=bytes([self.current])
            elif code==1:self.normally=payload[0];data=b""
            elif code==9:self.pulse=int.from_bytes(payload,"big");data=b""
            elif code==5:self.current=payload[0];data=b""
            else:raise AssertionError('unexpected relay write')
        elif code==11:
            index=payload[0]-1
            if index>=len(self.raws):return Mock(payload=b"\x01")
            data=self.raws[index]
        elif code==3:self.raws=[];data=b""
        elif code==1:
            if len(self.raws)+1==self.fail_number:raise HoboProtocolError('simulated write failure')
            self.raws.append(payload);data=bytes([len(self.raws)])
        else:raise AssertionError('unexpected alarm command')
        return Mock(payload=b"\0"+data)


def rule(**kw):
    return {"channel":CHANNEL["key"],"low":None,"high":100,"sample_count":3,"action":"activate","auto_clear":True,"enabled":True,**kw}


def snapshot(native):
    return {"serial":INFO["serial"],"archive":INFO,"sensors":SENSORS,"alarms":read_configuration(native.client,SENSORS)}


def plan(native,rules=None):
    return preview_configuration({"normally":"open","pulse_ms":1000,"rules":rules if rules is not None else [rule()]},snapshot(native))


